export const plans = [
  { id: "120", label: "120 km/day", km: 120, multiplier: 0.72 },
  { id: "240", label: "240 km/day", km: 240, multiplier: 0.86 },
  { id: "440", label: "440 km/day", km: 440, multiplier: 1 },
];

export const priceForPlan = (car, planId) => {
  const plan = plans.find((p) => p.id === planId) ?? plans[2];
  return Math.round((car.price * plan.multiplier) / 10) * 10;
};

export const cars = base.map((car) => ({
  ...car,
  priceFrom: priceForPlan(car, "120"),
  extraKmCharge: Math.max(6, Math.round(car.price / 420)),
  deposit: car.price > 4500 ? 5000 : 3000,
}));

export const getCarById = (id) => cars.find((car) => car.id === id);

export const brands = [...new Set(cars.map((c) => c.brand))].sort();
export const segments = [...new Set(cars.map((c) => c.segment))].sort();
export const fuels = [...new Set(cars.map((c) => c.fuel))].sort();
export const transmissions = [...new Set(cars.map((c) => c.transmission))].sort();

export const priceBounds = {
  min: Math.min(...cars.map((c) => c.priceFrom)),
  max: Math.max(...cars.map((c) => c.priceFrom)),
};

export default cars;
